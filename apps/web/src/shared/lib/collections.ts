import { limit, orderBy, query, where } from 'firebase/firestore';
import type {
  Album,
  Coupon,
  Duel,
  HallOfFameEdition,
  LeaderboardEntry,
  League,
  LongTermPrediction,
  Match,
  MatchEvent,
  Medal,
  OwnedSticker,
  Photo,
  Player,
  PlayerStats,
  Post,
  Prediction,
  Registration,
  SiteSettings,
  Sticker,
  StickerPack,
  Team,
  Tournament,
  Trade,
  UserAchievement,
  UserCoupon,
  UserEdition,
  UserProfile,
  Video,
  WallMessage,
} from '@copa/shared';
import { col, ref } from './data';

type WithId<T> = T & { id: string };
type Achievement = WithId<UserAchievement & { achievementId: string }>;
type Member = { id: string; displayName: string; joinedAt: number };

export const refs = {
  settings: () => ref<SiteSettings & { id: string }>('settings/site'),
  tournament: (id: string) => ref<Tournament>(`tournaments/${id}`),
  match: (id: string) => ref<Match>(`matches/${id}`),
  post: (id: string) => ref<Post>(`posts/${id}`),
  album: (id: string) => ref<Album>(`albums/${id}`),
  team: (id: string) => ref<Team>(`teams/${id}`),
  player: (id: string) => ref<Player>(`players/${id}`),
  playerStats: (id: string) => ref<PlayerStats>(`playerStats/${id}`),
  user: (uid: string) => ref<UserProfile>(`users/${uid}`),
  edition: (uid: string, tid: string) => ref<UserEdition>(`users/${uid}/editions/${tid}`),
  medal: (uid: string, tid: string) => ref<Medal>(`users/${uid}/medals/${tid}`),
  prediction: (matchId: string, uid: string) => ref<Prediction>(`predictions/${matchId}_${uid}`),
  longTerm: (tid: string, uid: string) => ref<LongTermPrediction>(`longTermPredictions/${tid}_${uid}`),
  leaderboard: (tid: string, uid: string) => ref<LeaderboardEntry>(`leaderboard/${tid}_${uid}`),
  league: (id: string) => ref<League>(`leagues/${id}`),
  hallOfFame: (tid: string) => ref<HallOfFameEdition>(`hallOfFame/${tid}`),
  mvpVote: (matchId: string, uid: string) => ref<{ id: string; playerId: string; createdAt: number }>(`matches/${matchId}/mvpVotes/${uid}`),
  cupVote: (tid: string, uid: string) => ref<{ id: string; playerId: string; createdAt: number }>(`tournaments/${tid}/mvpVotes/${uid}`),
  checkin: (matchId: string, uid: string) => ref<{ id: string; createdAt: number }>(`checkins/${matchId}_${uid}`),
};

export const cols = {
  teams: () => col<Team>('teams'),
  players: () => col<Player>('players'),
  matches: () => col<Match>('matches'),
  events: (matchId: string) => col<MatchEvent>(`matches/${matchId}/events`),
  posts: () => col<Post>('posts'),
  albums: () => col<Album>('albums'),
  photos: (albumId: string) => col<Photo>(`albums/${albumId}/photos`),
  videos: () => col<Video>('videos'),
  predictions: () => col<Prediction>('predictions'),
  leaderboard: () => col<LeaderboardEntry>('leaderboard'),
  leagues: () => col<League>('leagues'),
  leagueMembers: (id: string) => col<Member>(`leagues/${id}/members`),
  duels: () => col<Duel>('duels'),
  wall: () => col<WallMessage>('wallMessages'),
  playerStats: () => col<PlayerStats>('playerStats'),
  hallOfFame: () => col<HallOfFameEdition>('hallOfFame'),
  stickers: () => col<Sticker>('stickers'),
  collection: (uid: string) => col<OwnedSticker>(`users/${uid}/collection`),
  packs: (uid: string) => col<StickerPack>(`users/${uid}/packs`),
  achievements: (uid: string) => col<Achievement>(`users/${uid}/achievements`),
  medals: (uid: string) => col<Medal>(`users/${uid}/medals`),
  userCoupons: (uid: string) => col<UserCoupon>(`users/${uid}/coupons`),
  trades: () => col<Trade>('trades'),
  coupons: () => col<Coupon>('coupons'),
  registrations: () => col<Registration>('registrations'),
  users: () => col<UserProfile>('users'),
};

export const queries = {
  teams: (tid: string) => query(cols.teams(), where('tournamentId', '==', tid)),
  players: (tid: string) => query(cols.players(), where('tournamentId', '==', tid)),
  teamPlayers: (teamId: string) => query(cols.players(), where('teamId', '==', teamId)),
  matches: (tid: string) => query(cols.matches(), where('tournamentId', '==', tid), orderBy('order', 'asc')),
  events: (matchId: string) => query(cols.events(matchId), orderBy('createdAt', 'asc')),
  publishedPosts: (tid: string, max = 30) =>
    query(cols.posts(), where('tournamentId', '==', tid), where('status', '==', 'published'), orderBy('publishedAt', 'desc'), limit(max)),
  allPosts: (tid: string) => query(cols.posts(), where('tournamentId', '==', tid), orderBy('updatedAt', 'desc')),
  postBySlug: (slug: string) => query(cols.posts(), where('slug', '==', slug), where('status', '==', 'published'), limit(1)),
  videos: (tid: string) => query(cols.videos(), where('tournamentId', '==', tid), orderBy('publishedAt', 'desc')),
  albums: (tid: string) => query(cols.albums(), where('tournamentId', '==', tid), orderBy('createdAt', 'desc')),
  photos: (albumId: string) => query(cols.photos(albumId), orderBy('order', 'asc')),
  leaderboard: (tid: string, max = 100) =>
    query(cols.leaderboard(), where('tournamentId', '==', tid), orderBy('totalPoints', 'desc'), orderBy('exactScores', 'desc'), limit(max)),
  leagueBoard: (leagueId: string) => query(cols.leaderboard(), where('leagueIds', 'array-contains', leagueId), orderBy('totalPoints', 'desc')),
  myPredictions: (tid: string, uid: string) => query(cols.predictions(), where('tournamentId', '==', tid), where('uid', '==', uid)),
  myLeagues: (tid: string, uid: string) => query(cols.leaderboard(), where('tournamentId', '==', tid), where('uid', '==', uid), limit(1)),
  duelsAsChallenger: (uid: string) => query(cols.duels(), where('challengerUid', '==', uid)),
  duelsAsOpponent: (uid: string) => query(cols.duels(), where('opponentUid', '==', uid)),
  approvedWall: (tid: string, max = 12) =>
    query(cols.wall(), where('tournamentId', '==', tid), where('status', '==', 'approved'), orderBy('createdAt', 'desc'), limit(max)),
  pendingWall: (tid: string) => query(cols.wall(), where('tournamentId', '==', tid), where('status', '==', 'pending'), orderBy('createdAt', 'desc')),
  topScorers: (tid: string) => query(cols.playerStats(), where('tournamentId', '==', tid), orderBy('goals', 'desc'), limit(50)),
  playerStats: (tid: string) => query(cols.playerStats(), where('tournamentId', '==', tid)),
  stickers: (tid: string) => query(cols.stickers(), where('tournamentId', '==', tid), orderBy('number', 'asc')),
  myCollection: (uid: string, tid: string) => query(cols.collection(uid), where('tournamentId', '==', tid)),
  myPacks: (uid: string) => query(cols.packs(uid), where('opened', '==', false)),
  myAchievements: (uid: string) => query(cols.achievements(uid)),
  tradesFrom: (uid: string) => query(cols.trades(), where('fromUid', '==', uid)),
  tradesTo: (uid: string) => query(cols.trades(), where('toUid', '==', uid)),
  coupons: (tid: string) => query(cols.coupons(), where('tournamentId', '==', tid)),
  registrations: (tid: string) => query(cols.registrations(), where('tournamentId', '==', tid), orderBy('createdAt', 'desc')),
  myRegistrations: (uid: string) => query(cols.registrations(), where('submittedBy', '==', uid)),
  users: (max = 200) => query(cols.users(), orderBy('createdAt', 'desc'), limit(max)),
};
